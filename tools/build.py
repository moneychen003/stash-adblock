"""Build both clients from the same reviewed upstream and local repairs."""
from pathlib import Path
import argparse,hashlib,json
import yaml
from compile_fmz import compile_source
from render_shadowrocket import render
ROOT=Path(__file__).resolve().parents[1]
def digest(data):return hashlib.sha256(data).hexdigest()
def write_or_check(path,text,check):
    if check:assert path.read_text()==text,'Generated file differs: '+str(path.relative_to(ROOT))
    else:path.parent.mkdir(exist_ok=True);path.write_text(text)
def build(check=False):
    compile_source(check)
    config=json.loads((ROOT/'sources/config.json').read_text())
    version=json.loads((ROOT/'sources/version.json').read_text())
    stash='# Generated by tools/build.py; edit the shared sources instead.\n'+yaml.safe_dump(config,allow_unicode=True,sort_keys=False,width=120)
    shadow=render(config,version)
    products={'stash-adblock.stoverride':stash,'stash-adblock.shadowrocket.module':shadow}
    for name,text in products.items():write_or_check(ROOT/'rules'/name,text,check)
    h=config['http'];counts={'rules':len(config['rules']),'url_rewrites':len(h['url-rewrite']),'body_rewrites':len(h['body-rewrite']),'mitm_hosts':len(h['mitm']),'script_bindings':len(h['script']),'script_providers':len(config['script-providers']),'static_responses':len(h.get('mock',[]))}
    manifest={'version':version['version'],'configuration_sha256':digest(stash.encode()),'common_source_sha256':digest((ROOT/'sources/config.json').read_bytes()),'counts':counts,'products':{name:{'sha256':digest(text.encode()),'bytes':len(text.encode())} for name,text in products.items()},'local_scripts':{p.name:digest(p.read_bytes()) for p in sorted((ROOT/'scripts').glob('*.js'))}}
    write_or_check(ROOT/'rules/manifest.json',json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',check)
    return manifest
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();print(json.dumps(build(args.check),ensure_ascii=False))
