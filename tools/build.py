"""Build the reviewed public source into the Stash subscription."""
from pathlib import Path
import argparse,hashlib,json
import yaml
from compile_fmz import compile_source
ROOT=Path(__file__).resolve().parents[1]
def build(check=False):
 compile_source(check)
 config=json.loads((ROOT/'sources/config.json').read_text())
 text='# Generated by tools/build.py; edit sources/config.json instead.\n'+yaml.safe_dump(config,allow_unicode=True,sort_keys=False,width=120)
 path=ROOT/'rules/stash-adblock.stoverride'
 if check:
  assert path.read_text()==text,'Generated subscription differs; run python tools/build.py'
 else:path.parent.mkdir(exist_ok=True);path.write_text(text)
 manifest={'version':json.loads((ROOT/'sources/version.json').read_text())['version'],'configuration_sha256':hashlib.sha256(text.encode()).hexdigest(),'counts':{'rules':len(config['rules']),'url_rewrites':len(config['http']['url-rewrite']),'body_rewrites':len(config['http']['body-rewrite']),'mitm_hosts':len(config['http']['mitm']),'script_bindings':len(config['http']['script']),'script_providers':len(config['script-providers'])},'local_scripts':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((ROOT/'scripts').glob('*.js'))}}
 target=ROOT/'rules/manifest.json';body=json.dumps(manifest,ensure_ascii=False,indent=2)+'\n'
 if check:assert target.read_text()==body,'Manifest differs'
 else:target.write_text(body)
 return manifest
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();print(json.dumps(build(args.check),ensure_ascii=False))
